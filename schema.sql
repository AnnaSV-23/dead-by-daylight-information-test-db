DROP TABLE IF EXISTS killers CASCADE;
DROP TABLE IF EXISTS survivors CASCADE;
DROP TABLE IF EXISTS maps CASCADE;
DROP TABLE IF EXISTS killer_perks CASCADE;
DROP TABLE IF EXISTS survivor_perks CASCADE;
DROP TABLE IF EXISTS chapters CASCADE;


CREATE TABLE chapters (
	chapter INT GENERATED ALWAYS AS IDENTITY (START WITH 0 MINVALUE 0) PRIMARY KEY,
	chapter_title TEXT NOT NULL UNIQUE,
	release_date DATE
);

CREATE TABLE survivor_perks (
	perk_name VARCHAR(100) PRIMARY KEY,
	surv_name VARCHAR(100)
);

CREATE TABLE killer_perks (
	perk_name VARCHAR(100) PRIMARY KEY,
	klr_name VARCHAR(100)
);

CREATE TABLE maps (
	map_name VARCHAR(100) PRIMARY KEY,
	map_chapter INT
);


CREATE TABLE survivors (
	surv_name VARCHAR(100) PRIMARY KEY,
	surv_chapter INT NOT NULL REFERENCES chapters(chapter) ON DELETE RESTRICT
);

CREATE TABLE killers (
	klr_name VARCHAR(100) PRIMARY KEY,
	klr_pregame_name VARCHAR(100),
	klr_chapter INT NOT NULL REFERENCES chapters(chapter) ON DELETE RESTRICT,
	klr_power VARCHAR(100) NOT NULL,
	klr_speed FLOAT NOT NULL CHECK (klr_speed  0),
	klr_terror_radius INT NOT NULL CHECK (klr_terror_radius = 0)
);

